use serde::Deserialize;
use std::{fs, io, path::Path};

#[derive(Debug, Deserialize)]
pub struct ProfileCatalog {
    pub profiles: Vec<BootProfile>,
}

#[derive(Debug, Deserialize)]
pub struct BootProfile {
    pub id: String,
    pub name: String,
    pub iso: String,
    pub kernel: String,
    pub initrd: String,
    #[serde(default)]
    pub linux_args: Vec<String>,
}

fn safe_relative_path(value: &str) -> bool {
    !value.is_empty()
        && !value.starts_with('/')
        && !value.starts_with('\\')
        && value.split('/').all(|part| {
            !part.is_empty()
                && part != "."
                && part != ".."
                && part.chars().all(|c| c.is_ascii_alphanumeric() || "._-".contains(c))
        })
}

fn safe_id(value: &str) -> bool {
    !value.is_empty()
        && value.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

fn safe_label(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= 80
        && value.chars().all(|c| c.is_ascii_alphanumeric() || " ._()-".contains(c))
}

fn safe_argument(value: &str) -> bool {
    !value.is_empty()
        && value.chars().all(|c| c.is_ascii_alphanumeric() || "._/,:=+-".contains(c))
}

impl ProfileCatalog {
    pub fn load(path: &Path) -> Result<Self, Box<dyn std::error::Error>> {
        let contents = fs::read_to_string(path)?;
        let catalog: Self = toml::from_str(&contents)?;
        catalog.validate()?;
        Ok(catalog)
    }

    pub fn validate(&self) -> io::Result<()> {
        if self.profiles.is_empty() {
            return Err(io::Error::new(io::ErrorKind::InvalidInput, "profile catalog is empty"));
        }
        for profile in &self.profiles {
            if !safe_id(&profile.id) {
                return Err(io::Error::new(io::ErrorKind::InvalidInput, "unsafe profile id"));
            }
            if !safe_label(&profile.name) {
                return Err(io::Error::new(io::ErrorKind::InvalidInput, "unsafe profile name"));
            }
            for path in [&profile.iso, &profile.kernel, &profile.initrd] {
                if !safe_relative_path(path) {
                    return Err(io::Error::new(io::ErrorKind::InvalidInput, "profile paths must be safe relative paths"));
                }
            }
            if profile.linux_args.iter().any(|arg| !safe_argument(arg)) {
                return Err(io::Error::new(io::ErrorKind::InvalidInput, "unsafe kernel argument"));
            }
        }
        Ok(())
    }

    pub fn render_grub_config(&self) -> String {
        let mut output = String::from(
            "# Generated by Void Boot. Review profiles before using on physical media.\nset default=0\nset timeout=10\nset timeout_style=menu\nif loadfont unicode; then\n  set gfxmode=auto\n  insmod all_video\n  insmod gfxterm\n  terminal_output gfxterm\nfi\ninsmod part_gpt\ninsmod part_msdos\ninsmod fat\ninsmod ext2\ninsmod iso9660\ninsmod loopback\ninsmod linux\nset theme=$prefix/themes/void-boot/theme.txt\n\nmenuentry \"Void Boot - Firmware setup\" --class settings {\n  fwsetup\n}\n",
        );

        for profile in &self.profiles {
            let args = profile.linux_args.join(" ");
            output.push_str(&format!(
                "\nmenuentry \"{}\" --class atdev-linux {{\n  set isofile=\"/{}\"\n  if [ -f \"$isofile\" ]; then\n    loopback loop \"$isofile\"\n    linux (loop)/{} {}\n    initrd (loop)/{}\n  else\n    echo \"ISO not found: $isofile\"\n    sleep 5\n  fi\n}}\n",
                profile.name, profile.iso, profile.kernel, args, profile.initrd
            ));
        }
        output.push_str(
            "\nmenuentry \"Restart computer\" --class restart {\n  reboot\n}\nmenuentry \"Shut down\" --class shutdown {\n  halt\n}\n",
        );
        output
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> ProfileCatalog {
        ProfileCatalog {
            profiles: vec![BootProfile {
                id: "debian-live".into(),
                name: "Debian Live".into(),
                iso: "iso/debian-live.iso".into(),
                kernel: "live/vmlinuz".into(),
                initrd: "live/initrd.img".into(),
                linux_args: vec!["boot=live".into(), "components".into()],
            }],
        }
    }

    #[test]
    fn renders_graphical_grub_menu_with_profile_entries() {
        let rendered = sample().render_grub_config();
        assert!(rendered.contains("terminal_output gfxterm"));
        assert!(rendered.contains("menuentry \"Debian Live\""));
        assert!(rendered.contains("loopback loop \"$isofile\""));
        assert!(rendered.contains("linux (loop)/live/vmlinuz boot=live components"));
        assert!(rendered.contains("initrd (loop)/live/initrd.img"));
        assert!(rendered.contains("Restart computer"));
    }

    #[test]
    fn rejects_parent_directory_traversal() {
        let mut catalog = sample();
        catalog.profiles[0].kernel = "../outside/vmlinuz".into();
        assert!(catalog.validate().is_err());
    }

    #[test]
    fn rejects_grub_expression_in_kernel_arguments() {
        let mut catalog = sample();
        catalog.profiles[0].linux_args = vec!["quiet;reboot".into()];
        assert!(catalog.validate().is_err());
    }

    #[test]
    fn rejects_unsafe_menu_labels() {
        let mut catalog = sample();
        catalog.profiles[0].name = "Linux\"; reboot".into();
        assert!(catalog.validate().is_err());
    }
}
